import { chromium } from "playwright";
import fs from "fs";
const OUTS = ["/workspace/docs/entrega-sprint7/imagenes", "/opt/cursor/artifacts/entrega-sprint7"];
const N8N = process.env.N8N_URL || "http://127.0.0.1:5678";
const browser = await chromium.launch({ headless: true, args: ["--no-sandbox"] });
const page = await (await browser.newContext({ viewport: { width: 1400, height: 900 } })).newPage();
await page.goto(`${N8N}/signin`);
await page.locator('input[name="emailOrLdapLoginId"]').fill(process.env.N8N_EMAIL);
await page.locator('input[type="password"]').fill(process.env.N8N_PASSWORD);
await page.getByRole("button", { name: /sign in/i }).click();
await page.waitForTimeout(3000);
await page.goto(`${N8N}/workflow/milaev0000000001`, { waitUntil: "networkidle" });
await page.waitForTimeout(2500);
for (const o of OUTS) fs.mkdirSync(o, { recursive: true });
for (const o of OUTS) await page.screenshot({ path: `${o}/10_n8n_flujo_eventos_ia.png` });
await page.goto(`${N8N}/workflow/milaev0000000001/executions`, { waitUntil: "networkidle" });
await page.waitForTimeout(2500);
for (const o of OUTS) await page.screenshot({ path: `${o}/11_n8n_ejecuciones.png` });
await browser.close();
